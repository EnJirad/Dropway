/**
 * prompt + JSON schema ของการอ่านใบปะหน้า
 *
 * หลักคิด: ให้โมเดลอ่าน "ผู้รับ" ฝั่งเดียว แต่บังคับกติกาที่เคยทำให้อ่านผิดจริง
 * (ใบกลับหัว, ที่อยู่ยาวถูกย่อ, เลขเฟสโครงการปนกับบ้านเลขที่, ขยะจากหน้าจอแอปขนส่ง)
 * ไฟล์นี้ไม่มี key รูป หรือข้อมูลผู้รับ — ใช้ร่วมได้ทั้ง client และ server
 */

/** คำตอบที่ต้องการ: 6 ช่อง + ระดับความมั่นใจต่อช่อง (ใช้ตัดสินตอนรวมผลกับ OCR) */
export const LABEL_PROMPT = `คุณคือผู้อ่านฉลากพัสดุของไทย อ่านรูปแล้วดึงข้อมูล "ผู้รับ" เท่านั้น
ตอบเป็น JSON อย่างเดียว ห้ามมี markdown ห้ามมีข้อความอื่น เริ่มด้วย { จบด้วย }

รูปแบบ:
{"name":"","phone":"","houseNo":"","address":"","postalCode":"","tracking":"","confidence":{"name":"high","phone":"high","houseNo":"high","address":"high","postalCode":"high","tracking":"high"}}

[ทิศทางภาพ]
- ใบอาจเอียง ตะแคง หรือกลับหัว 180 องศา ทุกกรณีต้องอ่านได้ ห้ามตอบว่าอ่านไม่ออกเพราะภาพเอียง
- ห้ามใช้ตำแหน่งบน/ล่างในรูปตัดสินผู้ส่งกับผู้รับ ให้ดูคำกำกับบนใบเท่านั้น:
  ผู้รับ/ถึง/ส่งถึง/To/Deliver to  ·  ผู้ส่ง/จาก/From/Sender
- ถ้าใบมีทั้งสองฝั่ง ให้ใช้ฝั่ง "ผู้รับ" เท่านั้น ห้ามหยิบชื่อผู้ส่งมาใส่ name
- ถ้าเป็นภาพหน้าจอแอปขนส่งที่มีหลายการ์ด ให้เอาการ์ดที่อยู่กลางภาพหรือการ์ดแรก

[กติกาที่อยู่]
- address = ที่อยู่ผู้รับเต็ม ตั้งแต่บ้านเลขที่จนถึงจังหวัด/รหัสไปรษณีย์ (ไม่ใส่ชื่อ เบอร์ และรหัสไปรษณีย์)
- ห้ามตัดเลขที่บ้าน ถนน ซอย แขวง เขต ตำบล อำเภอ จังหวัด ทิ้งเด็ดขาด แม้ที่อยู่จะยาว
- เก็บชื่อหมู่บ้าน/คอนโด/อาคารไว้ด้วย เพราะใช้ค้นหาแผนที่ได้
- ชื่อโครงการที่มีเลขเฟสติด (เช่น "เดอะ คอนเนค 7/1", "The Connect 7/1")
  ตัวเลขนั้นคือเฟส/รุ่นโครงการ ไม่ใช่บ้านเลขที่ ให้คงไว้กับชื่อโครงการ
  บ้านเลขที่จริงคือเลขถัดมา (เช่น 247/147)
- ตัดสิ่งที่ไม่ใช่ที่ตั้งของบ้านทิ้ง เช่น "ข้างธนาคาร…", "ตรงข้ามปั๊ม…", "ร้านสะดวกซื้อ…"
- ห้ามนำข้อความเหล่านี้มาเป็นที่อยู่: รายละเอียดสินค้า, จำนวนพัสดุ, ระยะทาง, COD, ชื่อคลัง, ป้ายบริการ, "จัดส่งแล้ว N ครั้ง"
- แก้ชื่อที่อ่านเพี้ยนได้ (สระ/วรรณยุกต์หาย) ถ้ามั่นใจ แต่ห้ามเดาที่อยู่หรือชื่อที่ไม่มีบนใบ

[กติกาตัวเลข]
- phone: เฉพาะตัวเลข ขึ้นต้น 0 ความยาว 9-10 หลัก (ตัดขีด ช่องว่าง วงเล็บ)
- postalCode: 5 หลักเท่านั้น ถ้าไม่ชัดให้ ""
- houseNo: เลขที่บ้าน เช่น 12/3 (ไม่เอาเลขหมู่ ซอย หรือรหัสไปรษณีย์)
- tracking: เลขพัสดุที่อยู่ติดคำว่า เลขพัสดุ/tracking บนใบเดียวกันเท่านั้น
  รองรับทั้ง TH+ตัวเลข+ตัวอักษร และเลขล้วนยาว ถ้าใบมีหลายการ์ด ห้ามลอกข้ามการ์ด
  เลขอ้างอิงที่คู่กับวันที่/เวลา (เช่น 66857220226041 · 18-08 10:51) ไม่ใช่เลขพัสดุ

[ชื่อผู้รับ]
- เก็บคำนำหน้า (นาย/นาง/นางสาว/น.ส.) ถ้ามี
- ตัดเครื่องหมาย ~ หรือ * ต่อท้ายทิ้ง

[confidence]
- ใส่ high เมื่อเห็นชัดบนใบ, medium เมื่อพออ่านได้แต่มีบางส่วนไม่ชัด, low เมื่อเดา/เห็นไม่ครบ
- ช่องที่อ่านไม่ได้หรือไม่แน่ใจ = "" และ confidence = low ห้ามเดา ห้ามแต่ง`;

/** prompt รอบสอง: อ่านซ้ำเฉพาะช่องที่ยังขาด/ผิดรูป (ถูกกว่าอ่านใหม่ทั้งใบ) */
export function buildFocusPrompt(fields: string[]): string {
  const map: Record<string, string> = {
    name: "name = ชื่อผู้รับ (รวมคำนำหน้า)",
    phone: "phone = เบอร์โทรผู้รับ เฉพาะตัวเลข 9-10 หลัก ขึ้นต้น 0",
    houseNo: "houseNo = บ้านเลขที่ เช่น 12/3",
    address: "address = ที่อยู่ผู้รับเต็ม ห้ามตัดเลขที่บ้าน/ถนน/แขวง/เขต",
    postalCode: "postalCode = รหัสไปรษณีย์ 5 หลัก",
    tracking: "tracking = เลขพัสดุบนใบนี้เท่านั้น",
  };
  const wanted = fields.map((f) => map[f]).filter(Boolean).join("\n");
  return `${LABEL_PROMPT}

[งานรอบนี้ — อ่านซ้ำเฉพาะช่องที่ขาด]
${wanted}

ให้ตอบ JSON ครบทุกคีย์เหมือนเดิม แต่ใส่ค่าลงเฉพาะช่องด้านบน
ช่องอื่นที่ไม่ได้ขอให้ใส่ "" และ confidence = "low"
อ่านจากรูปเดิมเท่านั้น ห้ามเดาจากความจำหรือเดารูปแบบ`;
}

